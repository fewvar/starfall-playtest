/**
 * Детерминированный шум — основа процедурной генерации.
 * Одни и те же координаты всегда дают одно и то же содержимое,
 * поэтому конечная карта воспроизводима и не хранит далёкие чанки в памяти.
 */

/** Хеш пары координат с солью → беззнаковое 32-битное. */
export function hash32(x, y, salt = 0) {
  let h = x * 374761393 + y * 668265263 + salt * 2246822519;
  h = (h ^ (h >>> 13)) >>> 0;
  h = Math.imul(h, 1274126177) >>> 0;
  return (h ^ (h >>> 16)) >>> 0;
}

/** Генератор псевдослучайных чисел из семени: mulberry32. */
export function mulberry(seed) {
  let a = seed >>> 0;
  return function next() {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** Генератор, привязанный к клетке мира. */
export const rngAt = (x, y, salt = 0) => mulberry(hash32(x, y, salt));
