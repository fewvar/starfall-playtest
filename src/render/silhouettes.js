/**
 * СИЛУЭТЫ ВРАГОВ И БОССОВ.
 *
 * Вместо правильных многоугольников (`for i in n`) — заданные списки вершин
 * с вырезами и выступами: тип врага должен опознаваться по контуру, а не
 * только по цвету. Плюс 2-4 внутренние линии и акцентная точка ядра.
 *
 * Координаты НОРМИРОВАНЫ к радиусу: на отрисовке умножаются на e.r, поэтому
 * один и тот же силуэт годится и обычному врагу, и элите (она просто крупнее).
 *
 * Всё лежит в Float32Array и считается один раз при загрузке модуля: в кадре
 * остаётся только цикл lineTo по готовым числам — ровно столько же работы,
 * сколько было у правильных многоугольников.
 */

/** hull/lines задаются человекочитаемо, а в Float32Array переводятся один раз. */
function build(spec) {
  return {
    hull: new Float32Array(spec.hull.flat()),
    lines: new Float32Array((spec.lines ?? []).flat()),
    core: spec.core ?? null,
  };
}

